import Foundation
import MyTermCore

func checkCodexClusters() throws {
    let threadID = UUID().uuidString, association = UUID()
    let arguments = try CodexConnection.launchArguments(appExecutable: "/tmp/MyTerm.app/MyTerm", association: association,
        threadID: threadID, projectDirectory: "/tmp/GMI Dallas 集群")
    checkEqual(Array(arguments.suffix(4)), ["--cd", "/tmp/GMI Dallas 集群", "resume", threadID])
    checkEqual(arguments.contains("read-only"), true)
    checkEqual(arguments.contains("mcp_servers.myterm.env.MYTERM_CODEX_ASSOCIATION=\"" + association.uuidString + "\""), true)
    checkThrows(try CodexConnection.launchArguments(appExecutable: "/tmp/app", threadID: "--all", projectDirectory: "/tmp"))
    checkThrows(try CodexConnection.launchArguments(appExecutable: "/tmp/app", threadID: threadID))
    checkThrows(try CodexConnection.launchArguments(appExecutable: "/tmp/app", localDirectory: "/tmp", threadID: threadID, projectDirectory: "/tmp"))
    let root = FileManager.default.temporaryDirectory.appendingPathComponent("myterm-clusters-\(UUID())")
    defer { try? FileManager.default.removeItem(at: root) }
    var catalog = CodexClusterCatalog()
    let dallas = try catalog.addCluster("GMI Dallas")
    let london = try catalog.addCluster("GMI London")
    checkEqual(try catalog.addCluster("gmi dallas").id, dallas.id)
    checkFalse(dallas.folder.contains("/"))
    let longName = try catalog.addCluster(String(repeating: "集", count: 100))
    checkEqual(longName.folder.utf8.count < 255, true)
    checkEqual(try catalog.uniqueTitle("日常运维", cluster: dallas.id), "日常运维")
    checkThrows(try catalog.addCluster("\n"))
    checkThrows(try catalog.addCluster("bad\tname"))
    let now = Date(timeIntervalSince1970: 1792910000)
    let thread = UUID().uuidString
    catalog.conversations.append(.init(id: thread, clusterID: dallas.id, title: "日常运维", lastOpened: now))
    let name = try catalog.uniqueTitle("日常运维", cluster: dallas.id, now: now)
    checkEqual(name.hasPrefix("日常运维 · "), true)
    checkEqual(name.contains(":"), true)
    checkFalse(name.contains("(2)"))
    checkEqual(try catalog.uniqueTitle("日常运维", cluster: london.id), "日常运维")
    catalog.conversations.append(.init(id: UUID().uuidString, clusterID: dallas.id, title: name, lastOpened: now))
    checkFalse(try catalog.uniqueTitle("日常运维", cluster: dallas.id, now: now) == name)
    let server = UUID().uuidString; catalog.serverClusters[server] = dallas.id
    let url = root.appendingPathComponent("catalog.json")
    try catalog.save(to: url)
    let loaded = try CodexClusterCatalog.load(from: url)
    checkEqual(loaded.clusters, catalog.clusters)
    checkEqual(loaded.conversations, catalog.conversations)
    checkEqual(loaded.serverClusters[server], dallas.id)
    // Session metadata is independent of the transient SSH tab UUID.
    checkEqual(loaded.conversations[0].id, thread)
    // Changing the default pins existing cwd values, including legacy catalogs without path fields.
    let defaultDirectory = root.appendingPathComponent("CodexProjects")
    let oldPath = catalog.directoryURL(for: dallas, defaultDirectory: defaultDirectory)
    try catalog.renameCluster(dallas.id, name: "Dallas renamed")
    checkEqual(catalog.clusters.first { $0.id == dallas.id }?.folder, dallas.folder)
    checkEqual(catalog.directoryURL(for: catalog.clusters.first { $0.id == dallas.id }!, defaultDirectory: defaultDirectory), oldPath)
    checkEqual(catalog.serverClusters[server], dallas.id)
    checkEqual(catalog.conversations[0].id, thread)
    checkThrows(try catalog.renameCluster(dallas.id, name: "GMI London"))
    checkThrows(try catalog.renameCluster(dallas.id, name: "\n"))
    let defaultCluster = try catalog.ensureDefaultCluster()
    try catalog.renameCluster(defaultCluster.id, name: "My default")
    checkEqual(try catalog.ensureDefaultCluster().id, defaultCluster.id)
    try catalog.removeCluster(defaultCluster.id, openThreads: [])
    checkFalse(try catalog.ensureDefaultCluster().id == defaultCluster.id)
    checkEqual(CodexThreadRequestError(method: "thread/read", code: -32600,
        message: "no rollout found for thread id \(thread)").isMissingThread(thread), true)
    for message in ["Permission denied", "No such file or directory", "thread not found", "thread not loaded: \(thread)", "connection timed out"] {
        checkFalse(CodexThreadRequestError(method: "thread/read", code: -32600, message: message).isMissingThread(thread))
    }
    try catalog.setProjectsDirectory(root.appendingPathComponent("custom 项目").path, defaultDirectory: defaultDirectory)
    checkEqual(catalog.directoryURL(for: catalog.clusters.first { $0.id == dallas.id }!, defaultDirectory: defaultDirectory), oldPath)
    let newCluster = try catalog.addCluster("New cluster")
    let newPath = catalog.directoryURL(for: newCluster, defaultDirectory: defaultDirectory)
    checkEqual(newPath.deletingLastPathComponent().path, root.appendingPathComponent("custom 项目").path)
    try catalog.setProjectsDirectory(nil, defaultDirectory: defaultDirectory)
    checkEqual(catalog.directoryURL(for: catalog.clusters.first { $0.id == newCluster.id }!, defaultDirectory: defaultDirectory), newPath)
    checkThrows(try catalog.setProjectsDirectory("relative/path", defaultDirectory: defaultDirectory))
    checkThrows(try catalog.setProjectsDirectory("/tmp/bad\npath", defaultDirectory: defaultDirectory))
    try catalog.save(to: url)
    let paths = try CodexClusterCatalog.load(from: url)
    checkEqual(paths.directoryURL(for: paths.clusters.first { $0.id == dallas.id }!, defaultDirectory: defaultDirectory), oldPath)
    checkThrows(try catalog.removeCluster(dallas.id, openThreads: [thread]))
    checkThrows(try catalog.removeConversation(thread, openThreads: [thread]))
    checkEqual(catalog.serverClusters[server], dallas.id)
    try catalog.removeConversation(thread, openThreads: [])
    checkFalse(catalog.conversations.contains { $0.id == thread })
    try catalog.removeCluster(dallas.id, openThreads: [])
    checkEqual(catalog.serverClusters[server], nil)
    checkFalse(catalog.conversations.contains { $0.clusterID == dallas.id })
    checkEqual(catalog.clusters.contains { $0.id == london.id }, true)
    try catalog.save(to: url)
    checkFalse(try CodexClusterCatalog.load(from: url).clusters.contains { $0.id == dallas.id })
    try Data("damaged".utf8).write(to: url)
    checkThrows(try CodexClusterCatalog.load(from: url))
    checkEqual(try String(contentsOf: url, encoding: .utf8), "damaged")
}
